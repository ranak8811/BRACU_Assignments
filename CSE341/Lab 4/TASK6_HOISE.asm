ORG 100H

.DATA

P1 DB 'ENTER A HEX DIGIT: $'
P2 DB 0DH, 0AH, 'IN DECIMAL IT IS: $'
P3 DB 0DH, 0AH, 'DO YOU WANT TO DO IT AGAIN? (y/n): $'
P4 DB 0DH, 0AH, 'ILLEGAL CHARACTER - ENTER 0..9 OR A..F: $'

.CODE

ITERATE:

START:
MOV AH, 9
LEA DX, P1
INT 21H

MOV AH, 1
INT 21H
MOV BL, AL

CMP BL, 48
JL ILLEGAL
CMP BL, 57
JG CHECK

JMP PRINT

CHECK:
CMP BL, 65
JL ILLEGAL
CMP BL, 70
JG ILLEGAL
 
JMP PRINT

PRINT:
MOV AH, 9
LEA DX, P2
INT 21H

MOV AH, 2
MOV DL, BL
INT 21H

MOV AH, 9
LEA DX, P3
INT 21H 

MOV AH, 1
INT 21H
MOV CL, AL

CMP CL, 89
JE ITERATE


JMP END


ILLEGAL:
MOV AH, 9
LEA DX, P4
INT 21H
JMP ITERATE  

END:
RET