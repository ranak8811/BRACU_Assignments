.MODEL SMALL
.STACK 100H

.DATA
msg_input DB 'Enter a number (1-9): $'
msg_factors DB 'The factors are: $'
newline DB 0AH, 0DH, '$'

.CODE
MAIN PROC
MOV AX, @DATA
MOV DS, AX
MOV ES, AX

LEA DX, msg_input
MOV AH, 9
INT 21H

MOV AH, 1
INT 21H
SUB AL, '0'
MOV BL, AL

LEA DX, msg_factors
MOV AH, 9
INT 21H

MOV CX, 1

FIND_FACTORS:
XOR AX, AX
MOV AL, BL
XOR DX, DX
DIV CX
CMP DX, 0
JNE NOT_A_FACTOR

PUSH CX

NOT_A_FACTOR:
INC CX

MOV BX, 0
MOV BL, AL
CMP CX, BX
JLE FIND_FACTORS

MOV CX, 0

PRINT_FACTORS:
CMP SP, 100H
JE END_PROGRAM

POP DX
ADD DL, '0'
MOV AH, 2
INT 21H

LEA DX, newline
MOV AH, 9
INT 21H

JMP PRINT_FACTORS

END_PROGRAM:
MOV AH, 4CH
INT 21H

MAIN ENDP
END MAIN