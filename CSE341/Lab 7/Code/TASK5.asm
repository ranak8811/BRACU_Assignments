.MODEL SMALL

FIND_MAX MACRO NUM1, NUM2, NUM3
    MOV AX, NUM1
    CMP AX, NUM2
    JGE CHECK_THIRD
    MOV AX, NUM2

CHECK_THIRD:
    CMP AX, NUM3
    JGE MAX_FOUND
    MOV AX, NUM3

MAX_FOUND:
ENDM

.STACK 100H

.DATA
num1 DW 62
num2 DW 9
num3 DW 44
ANS  DW ?

.CODE
MAIN PROC
    MOV AX, @DATA
    MOV DS, AX

    FIND_MAX num1, num2, num3

    MOV ANS, AX

    MOV AH, 4CH
    INT 21H

MAIN ENDP

END MAIN
