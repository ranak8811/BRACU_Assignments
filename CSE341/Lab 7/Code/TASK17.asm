.MODEL SMALL
.STACK 100H

.DATA
newline DB 0AH, 0DH, '$'
N DW 50

.CODE
MAIN PROC
    MOV AX, @DATA
    MOV DS, AX

    MOV CX, 2
    MOV BX, N

CHECK_PRIME_NUMBERS:
    CALL IS_PRIME
    CMP AX, 1
    JNE NOT_PRIME

    CALL PRINT_NUMBER

NOT_PRIME:
    INC CX
    CMP CX, BX
    JLE CHECK_PRIME_NUMBERS

    MOV AH, 4CH
    INT 21H

MAIN ENDP

IS_PRIME PROC
    MOV AX, CX
    MOV BX, 2

    CMP CX, 2
    JB NOT_PRIME_FOUND

    CMP CX, 2
    JE PRIME_FOUND

    MOV DX, 0
    MOV BX, 2

PRIME_LOOP:
    MOV AX, CX
    DIV BX
    CMP DX, 0
    JE NOT_PRIME_FOUND

    INC BX
    MOV AX, CX
    MOV DX, 0
    DIV BX
    CMP BX, AX
    JAE PRIME_FOUND

    JMP PRIME_LOOP

PRIME_FOUND:
    MOV AX, 1
    RET

NOT_PRIME_FOUND:
    MOV AX, 0
    RET
IS_PRIME ENDP

PRINT_NUMBER PROC
    MOV AX, CX
    MOV BX, 10
    XOR CX, CX

CONVERT_LOOP:
    XOR DX, DX
    DIV BX
    PUSH DX
    INC CX
    CMP AX, 0
    JNE CONVERT_LOOP

PRINT_DIGITS:
    POP DX
    ADD DL, '0'
    MOV AH, 2
    INT 21H
    LOOP PRINT_DIGITS

    LEA DX, newline
    MOV AH, 9
    INT 21H

    RET
PRINT_NUMBER ENDP

END MAIN
